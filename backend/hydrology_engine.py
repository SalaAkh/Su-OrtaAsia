    def расчет_испарения_пенман_монтейт(self, площадь_зеркала_м2: float) -> float:
        """
        Расчет испарения по модифицированному уравнению Пенмана-Монтейта (м³/с).
        E_0 [мм/сут] преобразуется в секундный объемный расход с поверхности.
        """
        t = self.климат.температура_воздуха_c + self.климат.аномалия_температуры_засухи_c
        rh = max(5.0, self.климат.относительная_влажность_процент - self.климат.аномалия_температуры_засухи_c * 2.0)
        u2 = self.климат.скорость_ветра_мс
        rn = self.климат.солнечная_радиация_мдж
        
        # Давление насыщения водяного пара e_s (кПа)
        e_s = 0.6108 * math.exp((17.27 * t) / (t + 237.3))
        # Фактическое давление пара e_a (кПа)
        e_a = e_s * (rh / 100.0)
        # Наклон кривой давления пара delta (кПа/°C)
        delta = (4098.0 * e_s) / ((t + 237.3) ** 2)
        # Психрометрическая константа gamma (кПа/°C)
        gamma = 0.067
        
        # Испарение эталонное мм/сут
        число = 0.408 * delta * rn + gamma * (900.0 / (t + 273.0)) * u2 * (e_s - e_a)
        знаменатель = delta + gamma * (1.0 + 0.34 * u2)
        испарение_мм_сут = max(0.5, число / знаменатель)
        
        # Перевод в м³/с: мм/сут -> м/сут -> м/сек * площадь
        испарение_м_с = (испарение_мм_сут / 1000.0) / 86400.0
        расход_испарения_м3с = испарение_м_с * площадь_зеркала_м2
        return расход_испарения_м3с

    def расчет_фильтрации_костяков(self, расход_вход_м3с: float, длина_км: float, 
                                  тип_русла: str, глубина_м: float = 2.5) -> float:
        """
        Расчет фильтрационных потерь по эмпирической зависимости А.Н. Костякова.
        Q_filt = sigma * (K_f / 100) * B * L
        """
        if тип_русла == 'ЗЕМЛЯНОЙ':
            # Земляное песчано-суглинистое русло: потери до 35-45% на 100 км
            коэффициент_фильтрации = 0.0042
            коэффициент_деградации = 1.0 + 0.15 * (глубина_м / 2.0)
        elif тип_русла == 'БЕТОН':
            # Железобетонные плиты с трещинами в швах: 8-12%
            коэффициент_фильтрации = 0.00095
            коэффициент_деградации = 1.0
        elif тип_русла == 'ГЕОМЕМБРАНА':
            # Полимерная геомембрана: 2-3%
            коэффициент_фильтрации = 0.00025
            коэффициент_деградации = 1.0
        elif тип_русла == 'УМНАЯ_ТРУБА':
            # Закрытый герметичный композитный трубопровод с ультразвуковым контролем стыков: < 0.05%
            коэффициент_фильтрации = 0.00001
            коэффициент_деградации = 1.0
        else:
            коэффициент_фильтрации = 0.0020
            коэффициент_деградации = 1.0

        доля_потерь = 1.0 - math.exp(-коэффициент_фильтрации * коэффициент_деградации * длина_км)
        потери_фильтрации_м3с = расход_вход_м3с * min(0.65, доля_потерь)
        return потери_фильтрации_м3с

    def симуляция_засоления_почвы(self, глубина_грунтовых_вод_м: float, 
                                минерализация_воды_гл: float, 
                                тип_орошения: str, время_шаг_дней: float = 30.0) -> Dict[str, Any]:
        """
        Моделирование динамики капиллярного подъема и солончакообразования.
        Критическая глубина грунтовых вод H_кр ~ 2.0-2.5 м. При УГВ < H_кр происходит интенсивный
        подъем солей и образование белой солевой корки (солончака) на поверхности.
        """
        h_критическая = 2.2 # метры
        
        if тип_орошения == 'БОРОЗДКОВЫЙ_ЗЕМЛЯНОЙ':
            # Высокие потери на фильтрацию поднимают УГВ близко к поверхности
            эффективная_глубина = max(0.6, глубина_грунтовых_вод_м - 0.05 * (время_шаг_дней / 30.0))
            интенсивность_капиллярного_подъема = max(0.0, (h_критическая - эффективная_глубина) / h_критическая)
            
            # Накопление солей в пахотном слое (0-30 см)
            скорость_накопления_соли = интенсивность_капиллярного_подъема * минерализация_воды_гл * 0.45
            солевой_остаток_процент = 0.25 + скорость_накопления_соли * (время_шаг_дней / 30.0)
            солевой_остаток_процент = min(2.8, solevoy_ost := solevoy_ost if 'solevoy_ost' in locals() else солевой_остаток_процент)
            
            потери_урожайности_процент = min(85.0, max(0.0, (солевой_остаток_процент - 0.2) * 45.0))
            состояние_солончака = "СИЛЬНОЕ ЗАСОЛЕНИЕ (Белая солевая корка / Солончак)" if солевой_остаток_процент > 0.8 else "УМЕРЕННОЕ ЗАСОЛЕНИЕ"
            
        else: # КАПЕЛЬНОЕ_ОРОШЕНИЕ
            # Дозированный полив прямо в корневую зону, УГВ опускается на безопасную глубину
            эффективная_глубина = min(4.2, глубина_грунтовых_вод_м + 0.08 * (время_шаг_дней / 30.0))
            интенсивность_капиллярного_подъема = 0.0
            
            # Промывной локальный режим капельниц вымывает соли из зоны активных корней
            солевой_остаток_процент = max(0.08, 0.22 - 0.03 * (время_шаг_дней / 30.0))
            потери_урожайности_процент = 0.0
            состояние_солончака = "ОПТИМАЛЬНОЕ ПЛОДОРОДИЕ (Соли вымыты из корневой зоны)"

        return {
            "уровень_грунтовых_вод_м": round(эффективная_глубина, 2),
            "солевой_остаток_процент": round(солевой_остаток_процент, 3),
            "минерализация_гл": round(минерализация_воды_гл, 2),
            "потери_урожайности_процент": round(потери_урожайности_процент, 1),
            "статус_почвы": состояние_солончака
        }

    def прогноз_дефицита_городов(self, уровень_модернизации: float, 
                                засуха_активна: bool = False, 
                                маловодный_год: bool = False,
                                кош_тепа_отбор_км3: float = 0.0) -> Dict[str, Dict[str, Any]]:
        """
        Динамический прогноз дефицита питьевой воды для ключевых мегаполисов региона:
        Ташкент, Алматы, Бишкек, Душанбе, Самарканд.
        """
        результаты = {}
        
        # Коэффициенты климатического стресса
        мультипликатор_стока = 1.0
        if маловодный_год:
            мультипликатор_стока -= 0.28
        if засуха_активна:
            мультипликатор_стока -= 0.22
            
        for город, данные in self.города_параметры.items():
            население = данные["население"]
            норма_л = данные["норма_потребления_л_сут"]
            базовый_м3с = данные["базовый_забор_м3с"]
            доля_ледников = данные["доля_ледников"]
            емкость_резервуара = данные["емкость_резервуаров_млн_м3"]
            
            # Потребность города м³/с
            потребность_м3с = (население * норма_л / 1000.0) / 86400.0
            
            # Влияние модернизации сетей города (замена ветхих труб снижает потери в сетях с 38% до 6%)
            потери_в_городских_сетях = 0.38 * (1.0 - уровень_модернизации * 0.82)
            фактический_забор_требуемый = потребность_м3с * (1.0 + потери_в_городских_сетях)
            
            # Доступный приток из источника
            источник_приток = базовый_м3с * мультипликатор_стока
            
            # Самарканд и южные города дополнительно страдают от дефицита Зеравшана/Амударьи
            if город == "Самарканд":
                источник_приток *= max(0.35, 1.0 - (кош_тепа_отбор_км3 / 15.0) * 0.25)
            elif город == "Ташкент" and засуха_активна:
                # Падение горизонта Чарвакского водохранилища
                источник_приток *= 0.82
                
            дефицит_м3с = max(0.0, фактический_забор_требуемый - источник_приток)
            дефицит_процент = min(100.0, (дефицит_м3с / фактический_забор_требуемый) * 100.0)
            
            # Оценка дней до критического исчерпания аварийных резервуаров
            if дефицит_м3с > 0.05:
                дефицит_м3_сут = дефицит_м3с * 86400.0
                дни_до_истощения = int((емкость_резервуара * 1_000_000.0) / (дефицит_м3_сут + 1.0))
                дни_до_истощения = max(3, min(365, дни_до_истощения))
            else:
                дни_до_истощения = 999 # Запас стабилен
                
            результаты[город] = {
                "население": население,
                "потребность_м3с": round(потребность_м3с, 2),
                "доступный_приток_м3с": round(источник_приток, 2),
                "дефицит_процент": round(дефицит_процент, 1),
                "дни_до_истощения": дни_до_истощения,
                "уровень_риска": "КРИТИЧЕСКИЙ" if дефицит_процент > 25.0 else ("ВЫСОКИЙ" if дефицит_процент > 10.0 else "БЕЗОПАСНЫЙ")
            }
            
        return результаты

    def расчет_деградации_водоемов(self, уровень_модернизации: float,
                                   кош_тепа_отбор_км3: float,
                                   засуха_активна: bool) -> Dict[str, Dict[str, Any]]:
        """
        Расчет динамики наполнения ключевых водоемов (Токтогул, Нурек, Чарвак, Арал).
        """
        результаты = {}
        for имя, v in self.водоемы_состояние.items():
            приток = v.get("приток_м3с", 100.0)
            сброс = v.get("сброс_м3с", 100.0)
            полный = v["полный_объем_км3"]
            мертвый = v["мертвый_объем_км3"]
            текущий = v["текущий_объем_км3"]
            
            # Корректировка от Кош-Тепа для Туямуюна и Южного Арала
            if "Туямуюн" in имя or "Южный_Арал" in имя:
                коэффициент_кош_тепа = max(0.2, 1.0 - (кош_тепа_отбор_км3 / 15.0) * 0.65)
                приток *= коэффициент_кош_тепа
                
            if засуха_активна:
                приток *= 0.65
                
            # Эффект экономии от модернизации (снижение водозабора в ирригацию оставляет больше в русле)
            сэкономлено_водозабора = уровень_модернизации * 0.35
            сброс_скорректированный = max(мертвый * 0.1, сброс * (1.0 - сэкономлено_водозабора * 0.3))
            
            # Дельта объема (в км³ за год в динамике)
            дельта_км3_год = ((приток - сброс_скорректированный) * 86400 * 365) / 1_000_000_000.0
            прогноз_объем_км3 = max(мертвый * 0.4, min(полный, текущий + дельта_км3_год * 0.2))
            
            процент_наполнения = ((прогноз_объем_км3 - мертвый) / (полный - мертвый)) * 100.0
            процент_наполнения = max(0.0, min(100.0, процент_наполнения))
            
            результаты[имя] = {
                "текущий_объем_км3": round(прогноз_объем_км3, 2),
                "полный_объем_км3": полный,
                "мертвый_объем_км3": мертвый,
                "процент_наполнения": round(процент_наполнения, 1),
                "угроза_мертвого_объема": прогноз_объем_км3 <= (мертвый * 1.15)
            }
        return результаты
