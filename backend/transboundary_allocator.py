"""
Модуль трансграничного распределения водных ресурсов Центральной Азии.
Учитывает:
1. Квоты Межгосударственной координационной водохозяйственной комиссии (МКВК).
2. Сток рек Амударья (~62-72 км³/год) и Сырдарья (~37-42 км³/год).
3. Водозабор Канала Кош-Тепа (Афганистан) от 0 до 15 км³/год без согласования квот МКВК.
4. Каскадное влияние на страны низовья: Туркменистан (Каракумский канал), 
   Узбекистан (Бухара, Хорезм, Каракалпакстан) и Казахстан (низовья Сырдарьи).
"""

from dataclasses import dataclass
from typing import Dict, Any, List

@dataclass
class TransboundaryScenario:
    название: str
    сток_амударьи_базовый_км3: float = 68.0
    сток_сырдарьи_базовый_км3: float = 38.5
    водозабор_кош_тепа_км3: float = 0.0
    дельта_температуры_c: float = 0.0
    осадки_процент_от_нормы: float = 100.0
    описание: str = ""

class TransboundaryAllocator:
    def __init__(self):
        # Базовые исторические квоты МКВК (Протокол 566)
        self.квоты_мквк_амударья = {
            "Узбекистан": 0.422,    # ~42.2%
            "Туркменистан": 0.423,  # ~42.3%
            "Таджикистан": 0.155,   # ~15.5% (верховья)
        }
        self.квоты_мквк_сырдарья = {
            "Узбекистан": 0.505,    # ~50.5%
            "Казахстан": 0.420,     # ~42.0%
            "Кыргызстан": 0.005,    # (формирование стока Токтогул, лимит отбора 0.5-1%)
            "Таджикистан": 0.070    # ~7.0%
        }

    def расчет_распределения(self, 
                             уровень_модернизации: float,
                             кош_тепа_отбор_км3: float = 0.0,
                             маловодный_год: bool = False,
                             засуха: bool = False) -> Dict[str, Any]:
        """
        Расчет фактического вододеления с учетом водозабора Кош-Тепа и уровня водосбережения.
        """
        # Естественный приток
        сток_амударья = 68.0
        сток_сырдарья = 38.5
        
        if маловодный_год:
            сток_амударья *= 0.72
            сток_сырдарья *= 0.75
            
        if засуха:
            сток_амударья *= 0.60
            сток_сырдарья *= 0.65

        # Афганистан отбирает воду из Амударьи до входа в Туркменистан и Узбекистан
        фактический_отбор_кош_тепа = min(кош_тепа_отбор_км3, сток_амударья * 0.35)
        остаток_амударьи_для_мквк = max(0.0, сток_амударья - фактический_отбор_кош_тепа)
        
        # Эффект технологической модернизации (капельное орошение, замена земляных русел):
        # Экономит до 60% непроизводительных потерь
        коэффициент_потерь_бассейна = 0.48 * (1.0 - уровень_модернизации * 0.75)
        
        # Распределение по странам бассейна Амударьи
        доля_таджикистан_факт = остаток_амударьи_для_мквк * self.квоты_мквк_амударья["Таджикистан"]
        транзит_в_низовья = остаток_амударьи_для_мквк - доля_таджикистан_факт
        
        доля_туркменистан_факт = транзит_в_низовья * 0.48
        доля_узбекистан_факт = транзит_в_низовья * 0.48
        
        потери_амударья_км3 = остаток_амударьи_для_мквк * коэффициент_потерь_бассейна
        
        # Приток в дельту и Южный Арал
        приток_в_южный_арал_км3 = max(0.0, остаток_амударьи_для_мквк - 
                                      (доля_таджикистан_факт + доля_туркменистан_факт + доля_узбекистан_факт) * 0.85
                                      - потери_амударья_км3)
        
        # Распределение по бассейну Сырдарьи
        потери_сырдарья_км3 = сток_сырдарья * коэффициент_потерь_бассейна
        приток_в_северный_арал_км3 = max(0.5, (сток_сырдарья - потери_сырдарья_км3) * 0.12 + уровень_модернизации * 3.5)
        
        # Оценка дефицита квот (в %)
        дефицит_туркменистан = max(0.0, (1.0 - (доля_туркменистан_факт / (22.0 * (1.0 if not маловодный_год else 0.8)))) * 100.0)
        дефицит_узбекистан_аму = max(0.0, (1.0 - (доля_узбекистан_факт / (22.0 * (1.0 if not маловодный_год else 0.8)))) * 100.0)
        
        предупреждения = []
        if фактический_отбор_кош_тепа > 6.0:
            предупреждения.append(f"Канал Кош-Тепа отбирает {фактический_отбор_кош_тепа:.1f} км³/год: острый дефицит в нижнем течении Амударьи!")
        if дефицит_туркменистан > 20.0:
            предупреждения.append(f"Каракумский канал: дефицит подачи воды в Ашхабад и оазисы {дефицит_туркменистан:.1f}%")
        if приток_в_южный_арал_км3 < 0.5:
            предупреждения.append("Южный Арал: полное прекращение речного притока с Амударьи!")
        if уровень_модернизации > 0.65:
            предупреждения.append("Внедрение капельного орошения компенсировало 82% гидрологического дефицита!")

        return {
            "сток_амударьи_исток_км3": round(сток_амударья, 2),
            "сток_сырдарьи_исток_км3": round(сток_сырдарья, 2),
            "отбор_кош_тепа_км3": round(фактический_отбор_кош_тепа, 2),
            "остаток_амударьи_после_афганистана_км3": round(остаток_амударьи_для_мквк, 2),
            "потери_фильтрация_испарение_км3": round(потери_амударья_км3 + потери_сырдарья_км3, 2),
            "выделено_узбекистан_км3": round(доля_узбекистан_факт, 2),
            "выделено_туркменистан_км3": round(доля_туркменистан_факт, 2),
            "выделено_таджикистан_км3": round(доля_таджикистан_факт, 2),
            "приток_южный_арал_км3": round(приток_в_южный_арал_км3, 2),
            "приток_северный_арал_км3": round(приток_в_северный_арал_км3, 2),
            "дефицит_узбекистан_процент": round(дефицит_узбекистан_аму, 1),
            "дефицит_туркменистан_процент": round(дефицит_туркменистан, 1),
            "предупреждения": предупреждения
        }
