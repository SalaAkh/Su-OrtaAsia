    def сгенерировать_отсчет_телеметрии(self, 
                                       уровень_модернизации: float, 
                                       засуха: bool = False,
                                       авария_утечка: bool = False) -> List[Dict[str, Any]]:
        """
        Генерация динамических отсчетов с физическим шумом измерений.
        """
        результаты = []
        текущее_время = time.time()
        
        for узел in self.датчики_узлы:
            запись = dict(узел)
            запись["временная_метка"] = текущее_время
            
            # Добавление микро-флуктуаций датчиков (Гауссовский шум)
            шум = random.gauss(0, 0.02)
            
            if "базовый_расход_м3с" in узел:
                расход = узел["базовый_расход_м3с"] * (1.0 + шум)
                if засуха:
                    расход *= 0.75
                # В режиме модернизации расход более ламинарный
                запись["расход_воды_м3с"] = round(расход, 3)
                
            if "базовое_давление_бар" in узел:
                давление = узел["базовое_давление_бар"] * (1.0 + шум * 0.5)
                # При аварии утечки давление резко падает
                if авария_утечка and ("TASH" in узел["id"] or "KRK" in узел["id"]):
                    давление *= 0.58
                    запись["статус"] = "ТРЕВОГА: РЕЗКОЕ ПАДЕНИЕ ДАВЛЕНИЯ / СВИЩ"
                    запись["вероятность_утечки_процент"] = 96.5
                else:
                    запись["вероятность_утечки_процент"] = max(1.0, round(5.0 * (1.0 - уровень_модернизации) + abs(шум * 10), 1))
                запись["давление_бар"] = round(давление, 2)
                
            if "базовая_влажность_процент" in узел:
                # Влажность почвы: при модернизации (капельный полив) стабильно 35-45% в корневой зоне
                if уровень_модернизации > 0.5:
                    влажность = 38.0 + уровень_модернизации * 8.0 + шум * 5.0
                    минерализация = max(0.4, 1.2 - уровень_модернизации * 0.8 + шум * 0.1)
                else:
                    влажность = 14.0 - (5.0 if засуха else 0.0) + шум * 4.0
                    минерализация = 2.8 + (1.2 if засуха else 0.0) + шум * 0.3
                    
                запись["влажность_почвы_процент"] = round(max(5.0, min(65.0, влажность)), 1)
                запись["минерализация_воды_гл"] = round(max(0.2, минерализация), 2)
                
            if "уровень_м" in узел:
                дельта_уровня = (0.2 if уровень_модернизации > 0.5 else -0.3) + шум * 0.05
                запись["уровень_воды_м"] = round(узел["уровень_м"] + дельта_уровня, 2)
                
            # Состояние батареи и сигнала LoRaWAN
            запись["заряд_батареи_процент"] = round(94.0 + random.uniform(-2.0, 5.0), 1)
            запись["сигнал_lorawan_rssi_dbm"] = round(-78.0 + random.uniform(-8.0, 4.0), 1)
            
            результаты.append(запись)
            
        return результаты

    def анализ_аномалий_утечек(self, отсчеты: List[Dict[str, Any]]) -> List[str]:
        """
        Интеллектуальный поиск скрытых утечек по дисбалансу телеметрии.
        """
        тревоги = []
        for d in отсчеты:
            if d.get("вероятность_утечки_процент", 0) > 80.0:
                тревоги.append(f"АВАРИЯ НА УЗЛЕ {d['id']} ({d['название']}): гидроудар или скрытый свищ в русле!")
            if d.get("минерализация_воды_гл", 0) > 3.0:
                тревоги.append(f"ОПАСНОСТЬ СОЛОНЧАКА {d['id']}: минерализация {d['минерализация_воды_гл']} г/л превышает ПДК в 3 раза!")
        return тревоги
