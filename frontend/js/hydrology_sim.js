/**
 * Клиентский вычислительный движок гидродинамики и климатологии «Су-Орта Азия».
 * Обеспечивает мгновенный отклик физической модели в 60 FPS в браузере
 * и синхронизацию с серверным Python-бэкендом через WebSocket.
 */

class HydrologySimulationClient {
  constructor() {
    this.уровень_модернизации = 0.0; // 0.0 до 1.0 (слайдер 0-100)
    this.глобальное_обновление = true;
    this.засуха = false;
    this.маловодный_год = false;
    this.кош_тепа_отбор_км3 = 0.0; // 0 до 15 км³/год
    this.авария_утечка = false;
    this.время = 0;

    // Города Центральной Азии и параметры водопотребления
    this.города = {
      "Ташкент": {
        население: 3050000,
        норма_л_сут: 340,
        источник: "р. Чирчик / Чарвакское вдхр.",
        базовый_сток_м3с: 14.5,
        емкость_резервуара_млн_м3: 45.0,
        доля_ледников: 42
      },
      "Алматы": {
        население: 2250000,
        норма_л_сут: 310,
        источник: "р. Б. и М. Алматинка / ледники Туюксу",
        базовый_сток_м3с: 9.8,
        емкость_резервуара_млн_м3: 28.0,
        доля_ледников: 68
      },
      "Бишкек": {
        население: 1180000,
        норма_л_сут: 290,
        источник: "р. Ала-Арча / водозабор Орто-Алыш",
        базовый_сток_м3с: 5.2,
        емкость_резервуара_млн_м3: 16.0,
        доля_ледников: 55
      },
      "Душанбе": {
        население: 1220000,
        норма_л_сут: 320,
        источник: "р. Варзоб / Кафирниган",
        базовый_сток_м3с: 5.8,
        емкость_резервуара_млн_м3: 18.0,
        доля_ледников: 75
      },
      "Самарканд": {
        население: 1050000,
        норма_л_сут: 260,
        источник: "р. Зеравшан / Чопаната",
        базовый_сток_м3с: 4.5,
        емкость_резервуара_млн_м3: 12.0,
        доля_ледников: 35
      }
    };

    // Водохранилища и озера
    this.водоемы = {
      "Токтогульское": { полный: 19.5, мертвый: 5.5, текущий: 11.2, приток_база: 380, сброс_база: 420 },
      "Нурекское": { полный: 10.5, мертвый: 4.0, текущий: 8.9, приток_база: 650, сброс_база: 610 },
      "Чарвакское": { полный: 2.0, мертвый: 0.42, текущий: 1.45, приток_база: 180, сброс_база: 165 },
      "Туямуюн": { полный: 7.8, мертвый: 2.5, текущий: 3.1, приток_база: 290, сброс_база: 310 },
      "Северный_Арал": { полный: 27.0, мертвый: 10.0, текущий: 20.4, уровень: 42.1 },
      "Южный_Арал": { полный: 35.0, мертвый: 2.0, текущий: 5.8, уровень: 26.5 }
    };
  }

  /**
   * Вычисление полного гидрологического баланса текущего шага
   */
  вычислить_баланс() {
    const mod = this.уровень_модернизации;
    let сток_амударья = 68.0;
    let сток_сырдарья = 38.5;

    if (this.маловодный_год) {
      сток_амударья *= 0.72;
      сток_сырдарья *= 0.75;
    }
    if (this.засуха) {
      сток_амударья *= 0.58;
      сток_сырдарья *= 0.62;
    }

    // Водозабор канала Кош-Тепа
    const отбор_кош_тепа = Math.min(this.кош_тепа_отбор_км3, сток_амударья * 0.35);
    const амударья_после_афганистана = Math.max(0.0, сток_амударья - отбор_кош_тепа);

    // Коэффициент потерь: в земляных руслах 48-52%, при модернизации (умные трубы + геомембраны) снижается до 4-6%
    const коэф_потерь = 0.50 * (1.0 - mod * 0.88);
    const потери_фильтрация_км3 = (амударья_после_афганистана + сток_сырдарья) * коэф_потерь * 0.65;
    const потери_испарение_км3 = (амударья_после_афганистана + сток_сырдарья) * коэф_потерь * 0.35;

    // Сток в Южный Арал
    const забор_каракумы = Math.min(11.0, амударья_после_афганистана * 0.24);
    const забор_оазисы = Math.min(24.0, амударья_после_афганистана * 0.45 * (1.0 - mod * 0.35));
    const приток_южный_арал = Math.max(0.0, амударья_после_афганистана - забор_каракумы - забор_оазисы - (потери_фильтрация_км3 * 0.6));

    // Сток в Северный Арал (Малый Арал) через Кокаральскую плотину
    const приток_северный_арал = Math.max(0.6, (сток_сырдарья * 0.15) + mod * 4.2);

    // Засоление почвы
    // При паводковом/земляном орошении грунтовые воды поднимаются до 1.2 м (критический уровень)
    // Соли поднимаются капиллярами, образуя солончак (до 2.4% солей)
    // При капельном поливе УГВ на безопасной глубине 3.5 м, солевой остаток вымывается до 0.12%
    const глубина_угв_м = 1.2 + mod * 2.3;
    const солевой_остаток_процент = Math.max(0.08, 1.85 * (1.0 - mod * 0.92) + (this.засуха ? 0.45 : 0.0));
    const потери_урожайности = Math.min(85, Math.max(0, (солевой_остаток_процент - 0.2) * 50));

    // Городской прогноз дефицита
    const города_результат = {};
    for (const [имя, g] of Object.entries(this.города)) {
      const потребность_м3с = (g.население * g.норма_л_сут / 1000.0) / 86400.0;
      const потери_сетей = 0.38 * (1.0 - mod * 0.85);
      const требуемый_забор = потребность_м3с * (1.0 + потери_сетей);
      
      let доступный_приток = g.базовый_сток_м3с;
      if (this.маловодный_год) доступный_приток *= 0.74;
      if (this.засуха) доступный_приток *= 0.70;
      if (имя === "Самарканд") доступный_приток *= Math.max(0.3, 1.0 - (отбор_кош_тепа / 15.0) * 0.3);
      if (this.авария_утечка && имя === "Ташкент") доступный_приток *= 0.55;

      const дефицит_м3с = Math.max(0.0, требуемый_забор - доступный_приток);
      const дефицит_процент = Math.min(100.0, (дефицит_м3с / требуемый_забор) * 100.0);
      
      let дни_до_истощения = 999;
      if (дефицит_м3с > 0.05) {
        const суточный_дефицит = дефицит_м3с * 86400.0;
        дни_до_истощения = Math.max(3, Math.min(365, Math.round((g.емкость_резервуара_млн_м3 * 1e6) / суточный_дефицит)));
      }

      города_результат[имя] = {
        потребность_м3с: потребность_м3с.toFixed(2),
        дефицит_процент: дефицит_процент.toFixed(1),
        дни_до_истощения: дни_до_истощения,
        статус: дефицит_процент > 25 ? "КРИТИЧЕСКИЙ" : (дефицит_процент > 8 ? "ТРЕВОГА" : "НОРМА")
      };
    }

    // Состояние водоемов
    const водоемы_результат = {};
    for (const [имя, r] of Object.entries(this.водоемы)) {
      let объем = r.текущий;
      if (this.засуха) объем *= 0.78;
      if (this.маловодный_год) объем *= 0.88;
      if (имя === "Туямуюн" || имя === "Южный_Арал") {
        объем *= Math.max(0.25, 1.0 - (отбор_кош_тепа / 15.0) * 0.65);
      }
      объем += mod * (r.полный - r.мертвый) * 0.28;
      объем = Math.min(r.полный, Math.max(r.мертвый * 0.3, объем));

      const процент = Math.max(0, Math.min(100, ((объем - r.мертвый) / (r.полный - r.мертвый)) * 100));
      водоемы_результат[имя] = {
        текущий_объем: объем.toFixed(2),
        процент_наполнения: процент.toFixed(1),
        угроза_мертвого_объема: объем <= r.мертвый * 1.12
      };
    }

    // Предупреждения
    const предупреждения = [];
    if (отбор_кош_тепа > 6.0) {
      предупреждения.push({ тип: "danger", текст: `Канал Кош-Тепа отбирает ${отбор_кош_тепа.toFixed(1)} км³/год: катастрофический дефицит в Амударье!` });
    }
    if (this.засуха) {
      предупреждения.push({ тип: "danger", текст: "ЭКСТРЕМАЛЬНАЯ ЗАСУХА: Испарение превысило норму на 42%, ледниковый сток снижен!" });
    }
    if (this.маловодный_год) {
      предупреждения.push({ тип: "warning", текст: "МАЛОВОДНЫЙ ГОД: Дефицит притока в Токтогул и Нурек составляет -30%." });
    }
    if (this.авария_утечка) {
      предупреждения.push({ тип: "danger", текст: "ГИДРОУДАР И СВИЩ В МАГИСТРАЛИ: Потери давления на узле UZB-TASH-PR-02!" });
    }
    if (солевой_остаток_процент > 1.2) {
      предупреждения.push({ тип: "danger", текст: `КРИТИЧЕСКОЕ ЗАСОЛЕНИЕ ПОЧВ (${солевой_остаток_процент.toFixed(2)}%): Риск гибели 65% урожая в оазисах!` });
    }
    if (mod > 0.7) {
      предупреждения.push({ тип: "info", текст: "Капельный полив и закрытые композитные каналы сохраняют 24.5 км³ воды в год!" });
    }

    // Метрики нижнего HUD (по стилю image_0.png)
    const эффективность = Math.round(10 + mod * 85);
    const риск_текст = mod < 0.25 ? "Критический (10 лет)" : (mod < 0.65 ? "Умеренный" : "Безопасный");
    const потери_нераспределенные = Math.round(60 * (1.0 - mod * 0.88));
    const скрытые_утечки = Math.round(15 * (1.0 - mod * 0.95));

    return {
      сток_амударьи_км3: сток_амударья.toFixed(1),
      сток_сырдарьи_км3: сток_сырдарья.toFixed(1),
      отбор_кош_тепа_км3: отбор_кош_тепа.toFixed(1),
      потери_фильтрация_км3: потери_фильтрация_км3.toFixed(2),
      потери_испарение_км3: потери_испарение_км3.toFixed(2),
      приток_южный_арал_км3: приток_южный_арал.toFixed(2),
      приток_северный_арал_км3: приток_северный_арал.toFixed(2),
      глубина_угв_м: глубина_угв_м.toFixed(2),
      солевой_остаток_процент: солевой_остаток_процент.toFixed(2),
      потери_урожайности_процент: потери_урожайности.toFixed(1),
      эффективность_процент: эффективность,
      риск_текст: риск_текст,
      потери_ирригации_процент: потери_нераспределенные,
      скрытые_утечки_процент: скрытые_утечки,
      города: города_результат,
      водоемы: водоемы_результат,
      предупреждения: предупреждения
    };
  }
}
